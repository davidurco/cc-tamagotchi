//
//   #  ink, always on
//   .  off (transparent)
//   E  eye: on while the eyes are open; a closed eye keeps only its lowest row
//   M  mouth: on only while the mouth is open (eating, cheering)
//
// Creatures face right as drawn; a sprite walking left is mirrored. Sprites stand on their last row.

